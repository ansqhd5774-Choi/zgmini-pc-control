// INACTIVE Windows B entry preflight. Importing this module has zero effects.
// No CLI, workflow, provider request, DB open/create/write, or network action.
// The future trusted PRIVATE Windows entry must supply reviewed immutable pins
// and read-only Git/Core-lease/BLS-caller inspectors; Issue JSON cannot do so.
// This check NEVER authorizes execution: atomic recheck + B approval stay in
// the separately approved B entry.
import fs from 'node:fs';
import path from 'node:path';
import { validateR6OneShotRequest, verifyR6OneShotApprovalBytes } from './contract.mjs';

const WIN = path.win32;
const NODE = String.raw`E:\ZGmini\runtime\node.exe`;
const DATA_ROOT = String.raw`E:\ZGmini\data`;
const CODE = /^R6_B_[A-Z0-9_]{1,85}$/;
const SHA40 = /^[a-f0-9]{40}$/;
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;
const fail = code => { const e = Error(code); e.code = code; throw e; };
const norm = value => WIN.normalize(value).toLowerCase();
const inside = (child, parent) => {
  const rel = WIN.relative(parent, child);
  return rel !== '' && rel !== '..' && !rel.startsWith('..\\') && !WIN.isAbsolute(rel);
};
const safe = (input, fallback = 'R6_B_PREFLIGHT_UNKNOWN_STOP') =>
  typeof input === 'string' && CODE.test(input) ? input : fallback;

function verifiedExisting(io, target, type) {
  let stat, real;
  try {
    stat = io.lstatSync(target);
    real = io.realpathSync.native(target);
  } catch { fail(`R6_B_${type}_MISSING`); }
  if (stat.isSymbolicLink() || (type.endsWith('_DIR') ? !stat.isDirectory() : !stat.isFile()))
    fail(`R6_B_${type}_SHAPE_STOP`);
  return real;
}

function recent(at, nowMs) {
  if (typeof at !== 'string') return false;
  const ms = Date.parse(at);
  return Number.isFinite(ms) && ms <= nowMs && nowMs - ms <= 120_000;
}

/**
 * Read-only checks, parameterized only for isolated fixtures. In production:
 * `platform` MUST be the actual `process.platform`; `gitInspect`, `coreLease`,
 * and `blsCoverage` MUST be independent read-only PC inspections implemented
 * by a pinned private entry, never values copied from Issue body or callbacks
 * generated by the untrusted feature checkout. Passing a mocked callback in
 * unit tests does not establish a live Runtime proof.
 */
export async function checkR6BEntryPreflight({
  event, env, pins, manifestBytes, approvedDataBase,
  io = fs, platform = process.platform, now = new Date(),
  gitInspect, coreLease, blsCoverage,
} = {}) {
  let requestId = null;
  const blocked = code => ({ schema: 'ZGMINI_R6_B_ENTRY_PREFLIGHT_V1',
    status: 'BLOCKED', code: safe(code), requestId,
    allowProviderCalls: false, allowDbWrites: false, executable: false });
  try {
    if (!Number.isFinite(now?.getTime?.())) fail('R6_B_TIME_INVALID');
    // First validate the private Issue/owner/operation and immutable manifest
    // bytes BEFORE any filesystem or Git probe, especially before DB planning.
    const request = validateR6OneShotRequest(event, env, pins);
    requestId = request.requestId;
    const approvedManifest = verifyR6OneShotApprovalBytes(manifestBytes, pins);
    if (platform !== 'win32') fail('R6_B_WINDOWS_ONLY_STOP');
    if (typeof gitInspect !== 'function' || typeof coreLease !== 'function' ||
      typeof blsCoverage !== 'function') fail('R6_B_TRUSTED_PROBE_UNAVAILABLE');
    if (typeof env?.GITHUB_WORKSPACE !== 'string' ||
      !WIN.isAbsolute(env.GITHUB_WORKSPACE)) fail('R6_B_WORKSPACE_UNVERIFIED');
    if (typeof approvedDataBase !== 'string' || !WIN.isAbsolute(approvedDataBase))
      fail('R6_B_APPROVED_DB_BASE_UNVERIFIED');

    const workspace = verifiedExisting(io, env.GITHUB_WORKSPACE, 'WORKSPACE_DIR');
    const controlRoot = verifiedExisting(io, WIN.join(workspace, 'r6-control'), 'CONTROL_DIR');
    const sourceRoot = verifiedExisting(io, WIN.join(workspace, 'r6-source'), 'SOURCE_DIR');
    if (!inside(norm(controlRoot), norm(workspace)) ||
      !inside(norm(sourceRoot), norm(workspace))) fail('R6_B_CHECKOUT_ESCAPE_STOP');
    const node = verifiedExisting(io, NODE, 'NODE_FILE');
    if (norm(node) !== norm(NODE)) fail('R6_B_NODE_PATH_UNVERIFIED');
    const base = verifiedExisting(io, approvedDataBase, 'DATA_DIR');
    if (!inside(norm(base), norm(DATA_ROOT))) fail('R6_B_DATA_ROOT_ESCAPE_STOP');
    // Only existence/regular-file shape; opening/initializing core.sqlite here
    // would silently create or mutate user data and is strictly forbidden.
    const coreDb = verifiedExisting(io, WIN.join(base, 'storage', 'core.sqlite'), 'CORE_DB_FILE');
    if (!inside(norm(coreDb), norm(base))) fail('R6_B_DB_ESCAPE_STOP');
    // The approved manifest, not merely an Issue or arbitrary E: directory,
    // pins the exact Core DB target. This compares resolved existing bytes'
    // path and prevents a different valid-looking core.sqlite from passing.
    if (norm(coreDb) !== norm(approvedManifest.coreDatabasePath))
      fail('R6_B_APPROVED_CORE_DB_PATH_STOP');

    // The host's Git inspector must run fixed, read-only rev-parse/status on
    // both actual checkouts, not trust filenames or source SHA claims.
    const [control, source] = await Promise.all([
      gitInspect({ role: 'control', root: controlRoot }),
      gitInspect({ role: 'source', root: sourceRoot }),
    ]);
    if (!SHA40.test(control?.head) || !SHA40.test(source?.head) ||
      control.head !== pins.controlSha || source.head !== pins.sourceSha ||
      control.dirty !== false || source.dirty !== false)
      fail('R6_B_CHECKOUT_SHA_OR_DIRTY_STOP');

    const lease = await coreLease({ requestId, canonicalCoreDb: coreDb, now });
    if (lease?.status !== 'EXCLUSIVE_CORE_LEASE_VERIFIED' ||
      lease?.requestId !== requestId || lease?.canonicalCoreDb !== coreDb ||
      !UUID.test(lease?.leaseId ?? '') || !recent(lease?.observedAt, now.getTime()))
      fail('R6_B_CORE_LEASE_UNVERIFIED');
    const coverage = await blsCoverage({ requestId, canonicalBase: base, sourceSha: pins.sourceSha, now });
    if (coverage?.status !== 'ALL_BLS_UNREGISTERED_CALLERS_VERIFIED' ||
      coverage?.requestId !== requestId || coverage?.canonicalBase !== base ||
      coverage?.sourceSha !== pins.sourceSha ||
      coverage?.untrackedCallers !== 0 ||
      !Number.isSafeInteger(coverage?.trackedCallers) || coverage.trackedCallers < 1 ||
      !/^[a-f0-9]{64}$/.test(coverage?.journalAnchorSha256 ?? '') ||
      !recent(coverage?.observedAt, now.getTime()))
      fail('R6_B_BLS_COVERAGE_UNVERIFIED');

    return { schema: 'ZGMINI_R6_B_ENTRY_PREFLIGHT_V1',
      status: 'STRUCTURAL_PREFLIGHT_PASS_NOT_EXECUTABLE',
      code: 'R6_B_ENTRY_READONLY_CHECKS_PASS', requestId,
      verifiedCheckoutCount: 2, coreDbExisting: true,
      trackedBlsCallers: coverage.trackedCallers,
      allowProviderCalls: false, allowDbWrites: false, executable: false };
  } catch (error) {
    return blocked(error?.code ?? error?.message);
  }
}
