// #996 original-Windows GitHub REST GET-only port. NO CLI entrypoint, POST,
// Workflow mutation, token export, or C authorization. Credential verification
// is necessary for source provenance but not sufficient for operational C.
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {execFileSync} from 'node:child_process';

const REPO='ansqhd5774-Choi/zgmini-pc-control';
const ACTOR='ansqhd5774-Choi';
const ROOT='E:/ZGmini/automation/pc-maintenance';
const MAINTAINER_SHA='16064e29fea0e53e7769a24d93d75b6f5292cfc0';
const GH='C:/Program Files/GitHub CLI/gh.exe';
const need=(ok,code)=>{if(!ok)throw Object.assign(Error(code),{code});};
const ISSUE_LIST=/^issues\?state=all&sort=created&direction=desc&per_page=100&page=[1-9]\d{0,2}$/;
const COMMENT_LIST=/^issues\/[1-9]\d{0,9}\/comments\?per_page=100&page=[1-9]\d{0,2}$/;
const RESULT_PAIR=/^contents\/results\/[1-9]\d{0,19}-[1-9]\d{0,2}-seat-[1-6]\.(json|txt)$/;

function runGhApi(route){
 let output;
 try{output=execFileSync(GH,['api','--method','GET',route],{
  encoding:'utf8',windowsHide:true,timeout:30000,maxBuffer:3000000});}
 catch(e){
  // Only a fixed results/<run>-<attempt>-seat file may return 404.
  // All other failures, including authorization and connectivity, are hard
  // stops. Never include the raw stderr, token, or command in error output.
  if(route.startsWith('repos/'+REPO+'/contents/results/')&&
   /\bHTTP 404\b/i.test(String(e?.stderr??'')))return {status:404,data:{}};
  need(false,'C_GITHUB_READ_FAILED_OR_UNVERIFIABLE');
 }
 let data;
 try{data=JSON.parse(output);}catch{need(false,'C_GITHUB_RESPONSE_INVALID_JSON');}
 return {status:200,data};
}

export function create996NativeGitHubReadOnly({root=ROOT,testOnly=false,
 commandApi=runGhApi}={}){
 if(testOnly){
  need(process.platform!=='win32'&&path.isAbsolute(root)&&
   path.resolve(root).startsWith(path.resolve(os.tmpdir())+path.sep)&&
   path.basename(root).startsWith('zgmini-996-test-')&&
   commandApi!==runGhApi,'C_GITHUB_TEST_ROOT_OR_PORT_REJECTED');
 }else{
  need(process.platform==='win32'&&!process.env.GITHUB_ACTIONS&&
   !process.env.RUNNER_NAME&&
   path.win32.normalize(root).toLowerCase()===path.win32.normalize(ROOT).toLowerCase()&&
   commandApi===runGhApi,'C_ORIGINAL_WINDOWS_AUTHENTICATED_READER_REQUIRED');
 }
 let verified=false;
 const read=(route)=>{
  // A valid read-only route is entirely generated by the pinned reader;
  // never accept arbitrary GitHub API path or an Issue-controlled resource.
  need(typeof route==='string'&&
   (ISSUE_LIST.test(route)||COMMENT_LIST.test(route)||RESULT_PAIR.test(route)),
   'C_GITHUB_GET_ROUTE_NOT_ALLOWLISTED');
  need(verified,'C_GITHUB_READER_NOT_AUTHENTICATED');
  const response=commandApi(`repos/${REPO}/${route}`);
  need(response&&[200,404].includes(response.status),
   'C_GITHUB_READ_RESPONSE_UNVERIFIED');
  need(response.status===200||RESULT_PAIR.test(route),
   'C_GITHUB_LIST_READ_FAILED');
  return response;
 };
 return Object.freeze({
  authenticateReadOnly(){
   need(!verified,'C_GITHUB_READER_ALREADY_AUTHENTICATED');
   if(!testOnly){
    const file=path.join(root,'MAINTENANCE_INSTALL.json');
    const stat=fs.lstatSync(file);
    need(stat.isFile()&&!stat.isSymbolicLink()&&stat.size<200000,
     'C_GITHUB_ORIGINAL_MAINTAINER_UNVERIFIED');
    let m;
    try{m=JSON.parse(fs.readFileSync(file));}catch{
     need(false,'C_GITHUB_MAINTAINER_INVALID');
    }
    need(m.schema==='ZGMINI_PC_MAINTENANCE_INSTALL_V1'&&
     m.sourceSha===MAINTAINER_SHA,'C_GITHUB_ORIGINAL_MAINTAINER_UNVERIFIED');
   }
   const user=commandApi('user'),repo=commandApi(`repos/${REPO}`);
   need(user?.status===200&&user.data?.login===ACTOR&&
    repo?.status===200&&repo.data?.full_name===REPO&&
    repo.data.private===true,'C_GITHUB_READER_IDENTITY_MISMATCH');
   verified=true;
   return Object.freeze({repository:REPO,actor:ACTOR,private:true,
    readOnly:true,executionAuthorized:false});
  },
  get:read,
 });
}
